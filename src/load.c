// Load Weights

static float *read_floats(FILE *f, size_t n) {
  float *buffer = malloc(n * sizeof(float));
  if (! buffer) {
    perror("malloc");
    return NULL;
  }

  if (fread(buffer, sizeof(float), n, f) != n) {
    fprintf(stderr, "error: unexpected end of weight files\n");
    free(buffer);
    return NULL;
  }

  return buffer;
}

int load_weights(const char *path, Weights *w) {
  FILE *f = fopen(path, "rb");
  if (! f) {
    perror(path);
    return -1;
  }

  uint32_t header[4];
  if (fread(header, sizeof(uint32_t), 4, f) != 4) {
    fprintf(stderr, "error: could not read weights header\n");
    fclose(f);
    return -1;
  }
  w->vocab_size = header[0];
  w->embed_dim  = header[1];
  w->hidden_dim = header[2];
  w->output_dim = header[3];

  w->embedding  = read_floats(f, (size_t)w->vocab_size * w->embed_dim);
  w->fc1_weight = read_floats(f, (size_t)w->embed_dim  * w->hidden_dim);
  w->fc1_bias   = read_floats(f, w->hidden_dim);
  w->fc2_weight = read_floats(f, (size_t)w->hidden_dim * w->output_dim);
  w->fc2_bias   = read_floats(f, w->output_dim);

  fclose(f);

  if (!w->embedding || !w->fc1_weight || !w->fc1_bias || !w->fc2_weight || !w->fc2_bias) {
    free_weights(w);
    return -1;
  }
  return 0;
}

void free_weights(Weights *w) {
  free(w->embedding);
  free(w->fc1_weight);
  free(w->fc1_bias);
  free(w->fc2_weight);
  free(w->fc2_bias);
  w->embedding  = NULL;
  w->fc1_weight = NULL;
  w->fc1_bias   = NULL;
  w->fc2_weight = NULL;
  w->fc2_bias   = NULL;
}

// Load Vocab
//
// Disclaimer: the hash map part is generated by Claude

static uint32_t fnv1a(const char *s) {
  uint32_t h = 0x811c9dc5u;
  for (; *s; s++) {
    h ^= (unsigned char)*s;
    h *= 0x01000193u;
  }
  return h;
}

static void ht_insert(VocabBucket *buckets, uint32_t cap, const char *word, int index) {
  uint32_t slot = fnv1a(word) & (cap - 1);
  while (buckets[slot].index != -1) {
    slot = (slot + 1) & (cap - 1);
  }
  strncpy(buckets[slot].word, word, MAX_WORD_LEN - 1);
  buckets[slot].word[MAX_WORD_LEN - 1] = '\0';
  buckets[slot].index = index;
}

int load_vocab(const char *path, Vocab *v) {
  FILE *f = fopen(path, "rb");
  if (! f) {
    perror(path);
    return -1;
  }

  if (fread(&v->size, sizeof(uint32_t), 1, f) != 1) {
    fprintf(stderr, "error: could not read vocab header\n");
    fclose(f);
    return -1;
  }

  char (*raw)[MAX_WORD_LEN] = malloc((size_t)v->size * MAX_WORD_LEN);
  if (!raw) {
    perror("malloc");
    fclose(f);
    return -1;
  }
  if (fread(raw, MAX_WORD_LEN, v->size, f) != v->size) {
    fprintf(stderr, "error: unexpected end of vocab file\n");
    free(raw);
    fclose(f);
    return -1;
  }
  fclose(f);

  uint32_t cap = 1;
  while (cap < v->size * 2) {
    cap <<= 1;
  }
  v->cap = cap;

  v->buckets = malloc((size_t)cap * sizeof(VocabBucket));
  if (!v->buckets) {
    perror("malloc");
    free(raw);
    return -1;
  }
  for (uint32_t i = 0; i < cap; i++)
      v->buckets[i].index = -1;

  for (uint32_t i = 1; i < v->size; i++) {
      if (raw[i][0] != '\0')
          ht_insert(v->buckets, cap, raw[i], (int)i);
  }

  free(raw);
  return 0;
}

void free_vocab(Vocab *v) {
  free(v->buckets);
  v->buckets = NULL;
}

